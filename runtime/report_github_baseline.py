               '    *inject = input.inject;\n'
               '    int trig = input.action != 0;\n'
               '    if (trig && diag_on) diag_event("pad: %s shortcut", input.action == 2 ? "guide" : '
               '"menu");\n'
               '    if (input.action == 2) {\n'
               '        set_tab(SET_DIAGNOSTICS);\n'
               '        set_open(1);\n'
               '        guide_open(0);\n'
               '        dirty = 1;\n'
