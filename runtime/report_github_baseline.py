               '    if (row < 0 || !selectable(r[row])) return 1;\n'
               '    sel = row; editing = 0; dirty = 1;\n'
               '    Setting *s = r[row];\n'
               '    if (x >= VX) {\n'
               '        if (s->type == SET_SLIDER && !s->locked) { dragging = row; return portmenu_mouse(3, '
               'vx, vy, 0); }\n'
               '        if (s->type == SET_CHOICE && x < VX + 20) change(s, -1);\n'
               '        else activate(s);\n'
               '    } else if (s->type == SET_ACTION || s->type == SET_TEXT) activate(s);\n'
               '    return 1;\n'
