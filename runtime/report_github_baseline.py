               "// *inject gets buttons to send to the game anyway (a Create/View tap that wasn't a hold).\n"
               'enum { B_CROSS = 1, B_CIRCLE = 2, B_SQUARE = 4, B_TRIANGLE = 8, B_L1 = 16, B_R1 = 32, '
               'B_CREATE = 64, B_OPTIONS = 128, B_L3 = 256, B_R3 = 512 };\n'
               'uint32_t portmenu_pad(uint32_t phys, int up, int down, int left, int right, float lx, float '
               'ly, int home, int touchpad, int has_touchpad,\n'
               '                      uint32_t *inject) {\n'
               '    *inject = 0;\n'
               '    double now = host_ticks() / 1e9;\n'
               '    static uint32_t last_phys, hold_after_close;\n'
               '    static GuideShortcut shortcut;\n'
               '    GuideShortcutResult input = guide_shortcut(&shortcut, now, phys, home, touchpad, '
               'has_touchpad,\n'
               '        settings_get("controls.menu_button"), settings_get("controls.guide_button") == 0, '
               'is_open);\n'
