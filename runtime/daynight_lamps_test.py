#!/usr/bin/env python3
"""Section flare lifetime/ABI proof using the translated retail light loaders.

The fixture has two flares in one section: enabled queues 2 / 1 pack; Off,
public, missing include and a deliberately disabled load queue 0 / 0. The
broken control fails the same count oracle. No private assets => exit 3 after
the public/missing-data checks. --generate embeds only the private Rockport
bundle from ignored scratch; generated bytes never enter the public build.
--proof OFF_EVENTS ON_EVENTS ZERO_EVENTS FRAME checks one fixed game frame:
queued gain must cover every pack in view, actual draws must increase, and
the deliberately broken loader must equal Off with zero loads.
Game frame 3180: first Off/On/zero queued 0/15/0, drawn 0/5/0;
final still runs queued 0/15/0, drawn 0/6/0, On packs in view 2.
The zero-pack log substituted for On fails the same oracle (exit 1).
"""
from pathlib import Path
