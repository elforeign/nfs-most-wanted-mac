def retail_loaders():
    names = ['00501A10','00501BF0','007299E0','00729A30']
    found = {}
    for path in (ROOT / 'recomp/out').glob('speed_*.c'):
        text = path.read_text()
        for name in names:
            match = re.search(r'void f_'+name+r'\(Cpu \*restrict c\) \{.*?\n\}',text,re.S)
            if match:
                found[name]=match.group()
        if len(found)==len(names):
            return '\n'.join('void f_'+n+'(Cpu *c);' for n in names)+'\n'+'\n'.join(found[n] for n in names)
    return None


def run():
    zero = dict(world_queued=0, world_drawn=0, packs_in_view=0, loads=0)
    good = dict(world_queued=2, world_drawn=2, packs_in_view=1, loads=1)
    count_oracle(zero,good,zero)
    try:
        count_oracle(zero,zero,zero)
    except AssertionError:
        pass
    else:
        raise AssertionError('zero-pack control passed game count oracle')
    raw=fixture()
    assert decode(raw,4)==2
    for offset,value in [(4,len(raw)),(16+8,2),(16+0x50,3),(16+0x54,5),(128+44,14)]:
        bad=bytearray(raw)
        struct.pack_into('<I' if offset!=128+44 else '<B',bad,offset,value)
        try:
            decode(bad,4)
        except ValueError:
            continue
        raise AssertionError('malformed pack accepted')
    retail=retail_loaders()
    if retail is None:
        print('SKIP: translated retail light loaders absent')
        return 3
    with tempfile.TemporaryDirectory(prefix='daynight-lamps-') as tmp:
        temp=Path(tmp)
        (temp/'retail_loaders.inc').write_text(retail)
        (temp/'harness.c').write_text(HARNESS)
        (temp/'daynight_lamps_private.inc').write_text(emit([(4,raw)]))
        cmd=['clang','-w','-std=c11','-DRECOMP_ABICHECK','-I'+str(temp),'-I'+str(RUNTIME),'-I'+str(ROOT/'recomp'),
             '-include',str(ROOT/'recomp/out/funcs.h'),str(temp/'harness.c')]
        for label,flags,source in [('normal',[],SOURCE),('public',['-DNFS_PUBLIC=1'],SOURCE),
                                   ('broken',[],temp/'broken.c'),('missing',[],SOURCE)]:
            if label=='broken':
                source.write_text(SOURCE.read_text().replace('if (!info || M32(info+8)) return;', 'return;'))
            if label=='missing':
                (temp/'daynight_lamps_private.inc').unlink()
            binary=temp/label
            subprocess.run(cmd+flags+['-DTEST_SOURCE="'+str(source)+'"','-o',str(binary)],check=True,capture_output=True)
            for switch in [None,'0','on','1']:
                expect=int(label=='normal' and switch=='1')
                result=subprocess.run([str(binary),str(expect)]+([switch] if switch else []),capture_output=True,text=True)
                if result.returncode:
                    raise AssertionError(label+': '+result.stdout+result.stderr)
                print(label, switch, result.stdout.strip())
            if label=='broken':
                result=subprocess.run([str(binary),'1','1'],capture_output=True)
                assert result.returncode!=0, 'zero-pack hook passed the positive oracle'
    print('PASS daynight_lamps: native retail load/unload, Off/public/missing, broken positive oracle; 0 FAIL')
    return 0


if __name__=='__main__':
    if len(sys.argv)==3 and sys.argv[1]=='--generate':
        generate(sys.argv[2])
    elif len(sys.argv)==6 and sys.argv[1]=='--proof':
        game_proof(sys.argv[2:5],int(sys.argv[5]))
    else:
        try:
            raise SystemExit(run())
        except subprocess.CalledProcessError as exc:
            print(exc.stderr.decode() if isinstance(exc.stderr,bytes) else exc.stderr,file=sys.stderr)
            raise
