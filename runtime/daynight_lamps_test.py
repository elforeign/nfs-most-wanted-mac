ROOT = Path(__file__).resolve().parents[1]
RUNTIME = ROOT / 'runtime'
SOURCE = RUNTIME / 'daynight_lamps.c'


def count_oracle(off, on, zero):
    packs = on['packs_in_view']
    assert packs > 0 and on['world_queued']-off['world_queued'] >= packs, 'no queued lamp gain'
    assert on['world_drawn'] > off['world_drawn'], 'no visible flare submissions'
    assert (zero['world_queued'], zero['world_drawn']) == (off['world_queued'], off['world_drawn']), 'zero-pack control differs from Off'
    assert off['loads'] == zero['loads'] == 0 and on['loads'] > 0, 'pack load control'


def game_proof(paths, frame):
    rows = []
    for path in paths:
        with Path(path).open() as stream:
            matches = [line for line in stream if f'daynight_lamps: frame={frame} ' in line]
        assert len(matches) == 1, 'missing/duplicate fixed-frame diagnostic: '+str(path)
        rows.append({k:int(v) for k,v in re.findall(r'(\w+)=(\d+)',matches[0])})
    count_oracle(*rows)
    print('PASS game frame %d: Off/On/zero queued=%s drawn=%s; On packs=%d' %
          (frame, '/'.join(str(r['world_queued']) for r in rows),
           '/'.join(str(r['world_drawn']) for r in rows), rows[1]['packs_in_view']))


def decode(data, section):
    if len(data) < 8 or struct.unpack_from('<II', data) != (0x80135100, len(data)-8):
        raise ValueError('outer flare envelope')
    children = []
    p = 8
    while p < len(data):
        if p+8 > len(data):
            raise ValueError('truncated child')
        kind, size = struct.unpack_from('<II', data, p)
        start, end = (p+23)&~15, p+8+size
        if end > len(data) or start > end:
            raise ValueError('child extent')
        children.append((kind, data[start:end]))
        p = end
    if [c[0] for c in children] != [0x135101, 0x135102]:
        raise ValueError('flare child order')
    header, records = children[0][1], children[1][1]
    if len(header) != 96 or struct.unpack_from('<I', header, 8)[0] != 3:
        raise ValueError('flare header version/size')
    count = struct.unpack_from('<H', header, 0x50)[0]
    if not count or struct.unpack_from('<I', header, 0x54)[0] != section or not 0 <= section < 2800:
        raise ValueError('flare count/section binding')
    if len(records) != count*48 or any(header[:8]) or any(header[0x58:]):
        raise ValueError('flare record stride/runtime links')
    bounds = [struct.unpack_from('<3f', header, off) for off in (0x30, 0x40)]
    if not all(math.isfinite(v) for b in bounds for v in b) or any(a>b for a,b in zip(*bounds)):
        raise ValueError('flare bounds')
    for p in range(0, len(records), 48):
        row = records[p:p+48]
        xyz = struct.unpack_from('<3f', row, 0x10)
        if any(row[:16]) or struct.unpack_from('<f', row, 0x1c)[0] != 999.:
            raise ValueError('flare links/reflection cache')
        if row[0x20:] != bytes(12)+bytes([13,0,0,0]):
            raise ValueError('flare type/flags/direction')
        if not all(math.isfinite(v) and a<=v<=b for v,a,b in zip(xyz,*bounds)):
            raise ValueError('flare position/bounds')
    return count


def emit(packs):
    rows, blob = [], bytearray()
    for section, data in packs:
        decode(data, section)
        rows.append((section,len(blob),len(data)))
        blob.extend(data)
    return ('// Generated private section packs.\n'
            'static const unsigned char lamp_bytes[] = {\n'+
            '\n'.join(','.join(str(b) for b in blob[p:p+32])+',' for p in range(0,len(blob),32))+
            '\n};\nstatic const LampPack lamp_packs[] = {\n'+
            '\n'.join('{%d,%d,%d},'%r for r in rows)+
            '\n};\n#define LAMP_PACK_COUNT %d\n'%len(rows))


def generate(output):
    output = Path(output).resolve()
    if not output.is_relative_to(ROOT / 'recomp/out'):
        raise ValueError('private lamp output must be under recomp/out')
    if os.environ.get('NFS_PUBLIC') == '1':
        print('daynight lamps: public fallback')
        return
    include = output / 'daynight_lamps_private.inc'
    bundle = ROOT / '.metal-cache/daynight-lamps/export/rockport'
    files = sorted(bundle.glob('section-*.bun'))
    if not files:
        include.unlink(missing_ok=True)
        print('daynight lamps: private bundle absent; original world')
        return
    packs = sorted((int(p.stem.removeprefix('section-')),p.read_bytes()) for p in files)
    text = emit(packs)
    output.mkdir(parents=True, exist_ok=True)
    if not include.is_file() or include.read_text() != text:
        include.write_text(text)
    print('daynight lamps: %d Rockport packs, %d flares, %d bytes' %
          (len(packs),sum(decode(b,s) for s,b in packs),sum(len(b) for _,b in packs)))


def fixture():
    header = bytearray(96)
    struct.pack_into('<I',header,8,3)
    struct.pack_into('<3f',header,0x30,-10,-10,-10)
    struct.pack_into('<3f',header,0x40,10,10,10)
    struct.pack_into('<H',header,0x50,2)
    struct.pack_into('<I',header,0x54,4)
    records = bytearray(96)
    for i in range(2):
        struct.pack_into('<3ff',records,48*i+16,i,2,3,999)
        records[48*i+44] = 13
    payload = struct.pack('<II',0x135101,96)+header
    payload += struct.pack('<II',0x135102,104)+bytes([17])*8+records
    return struct.pack('<II',0x80135100,len(payload))+payload


