def main():
    material = (RT / 'materials.m').read_text()
    render = (RT / 'render.m').read_text()
    helper = material[material.index('#define CAR_PAINT_POW_MSL'):material.index('\n\nstatic const char car_paint_msl')]
    body = material[material.index('static const char car_paint_msl'):material.index('\n// BOOT_DIAG_CARPAINT_AB=1')]
    upload = function(render, 'paint_flake_texture').replace('paint_flake_volume(&bytes)', 'test_volume(&bytes)')
    begin = render.index('    if (pse->mat && mat_extra_texture(pse->mat) == MAT_TEX_CARNM) {      // materials.m R30')
    binding = render[begin:render.index('\n#if NFS_GAME == NFS_GAME_MW\n    if (daynight_sky_bind', begin)]
    with tempfile.TemporaryDirectory(prefix='paint-flake-') as tmp:
        d = Path(tmp)
        selection_check(d, material)
        shared = d / 'flake.dylib'
        run(['clang', '-shared', '-O1', RT / 'paint_flake.c', '-o', shared])
        lib = ctypes.CDLL(str(shared))
        lib.paint_flake_volume.restype = ctypes.POINTER(ctypes.c_uint8)
        n = ctypes.c_uint32()
        data = ctypes.string_at(lib.paint_flake_volume(ctypes.byref(n)), n.value)
        assert n.value == 149796 and data == reference()
        occupied = sum(x == 255 for x in data[3:32**3*4:4])
        assert .93 < occupied / 32**3 < .97
        lib.paint_flake_noise.restype = ctypes.POINTER(ctypes.c_uint8)
        width, height = ctypes.c_uint32(), ctypes.c_uint32()
        noise = lib.paint_flake_noise(ctypes.byref(width), ctypes.byref(height))
        assert width.value == height.value == 512
        assert set(ctypes.string_at(noise, 512*512*4)[3::4]) == {255}
        lib.paint_flake_fade_b.restype = ctypes.c_float
        lib.paint_flake_fade_b.argtypes = []
        assert lib.paint_flake_fade_b() == .25      # the console's B; the shader's A 1.2 makes zero at 4.8 m
        print('paint_flake_test: bytes=%d occupied=%d/32768 sha256=%s CPU PASS' % (n.value, occupied, hashlib.sha256(data).hexdigest()), flush=True)
        emit = d / 'emit.c'
        emit.write_text('#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n#include "paint_flake.h"\n#include "../host/shaders/sm_coverage.h"\n' +
                        '#define CAR_SHADOW_OFF16 ""\n#define PCS_CAR_SHADOW_FLOOR "0.2"\n' +
                        lits.text(None, 'port flake fixture') + '\n' + helper + '\n' + body +
                        '\nstatic int car_locallight_enabled(void){return 1;}\n' +
                        material[material.index('static const char car_local_math'):material.index('static char *car_local_shader')] +
                        '\n'.join(function(material, n) for n in ('dup_replace', 'edit', 'car_local_shader')) +
                        '\nint main(void){char *s=car_local_shader(strdup(car_paint_msl),0,0);if(!s)return 1;fputs(s,stdout);free(s);}\n')
        run(['clang', '-I', RT, emit, '-o', d / 'emit'])
        shader = d / 'paint.metal'
        shader.write_text(run([d / 'emit']).stdout)
        harness = d / 'fixture.m'
        harness.write_text(HARNESS.replace('@UPLOAD@', upload).replace('@BIND@', binding))
        run(['clang', '-O1', '-fobjc-arc', '-I', RT, harness, RT / 'paint_flake.c', '-framework', 'Foundation', '-framework', 'Metal', '-o', d / 'fixture'])
        good = subprocess.run([str(d / 'fixture'), str(shader)], capture_output=True, text=True)
        print(good.stderr, end='')
        if good.returncode == 3:
            return 3
        assert good.returncode == 0, 'generated paint has no visible effect'
        broken = run([d / 'fixture', shader, '--missing'], expected=1)
        print(broken.stderr, end='')
        assert 'changed=0 zero_metal=0 mid=0 far=0 nonfinite=0 missing=1' in broken.stderr
        proof = RT.parent / '.metal-cache' / 'paint-flake-proof.log'
        proof.parent.mkdir(exist_ok=True)
        proof.write_text(good.stderr + broken.stderr)
        print('paint_flake_test: production=0 missing-texture=1 PASS')
    return 0


