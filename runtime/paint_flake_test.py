def run(args, expected=0, **kw):
    p = subprocess.run([str(a) for a in args], capture_output=True, text=True, **kw)
    assert p.returncode == expected, p.stdout[-2000:] + p.stderr[-5000:]
    return p


def reference():
    state, inc = 0, 3
    def next32():
        nonlocal state
        old = state
        state = (old * 6364136223846793005 + inc) & ((1 << 64) - 1)
        x = (((old >> 18) ^ old) >> 27) & 0xffffffff
        rot = old >> 59
        return ((x >> rot) | (x << ((-rot) & 31))) & 0xffffffff
    next32()
    state = (state + 0x464c414b) & ((1 << 64) - 1)
    next32()
    def uniform():
        return (next32() + .5) / 4294967296
    b = bytearray()
    for _ in range(32 ** 3):
        occupied = uniform() < .95
        for _ in range(3):
            g = max(-1, min(1, math.sqrt(-2 * math.log(uniform())) * math.cos(2 * math.pi * uniform()))) / 2.9
            b.append(math.floor(127.5 * (1 + g) + .5))
        b.append(255 if occupied else 0)
    start, n = 0, 32
    while n > 1:
        m = n // 2
        for z in range(m):
            for y in range(m):
                for x in range(m):
                    for c in range(4):
                        b.append((4 + sum(b[start + 4 * (((2*z+dz)*n+2*y+dy)*n+2*x+dx)+c]
                                          for dz in range(2) for dy in range(2) for dx in range(2))) // 8)
        start += n ** 3 * 4
        n = m
    return bytes(b)


def selection_check(d, material):
    # Compile the real selector with unavailable console literals and resources.
    code = '''#include <stdint.h>
#include <stdlib.h>
#include <stdio.h>
#include <string.h>
#define X360_SHADER_LITS 0
static int flake=-1,diag_on,materials_flake_tint,materials_flake_force=-1;
static void diag_event(const char *s,...){(void)s;}
static const uint8_t *mat_grass_noise(uint32_t *w,uint32_t *h){(void)w;(void)h;return NULL;}
static const uint8_t *mat_grass_volume(uint32_t *b){(void)b;return NULL;}
'''
    code += '\n'.join(function(material, n) for n in
                      ('flake_on', 'materials_set_car_flake', 'mat_flake_volume_ok'))
    code += '\nint main(void){printf("%d %d\\n",flake_on(),mat_flake_volume_ok());}\n'
    (d / 'selection.c').write_text(code)
    run(['clang', '-Werror', d / 'selection.c', '-o', d / 'selection'])
    env = dict(PATH=os.environ['PATH'])
    for value, expected in ((None, '2 2'), ('pc', '0 0'), ('x360', '0 0'), ('generated', '2 2')):
        current = dict(env)
        if value is not None:
            current['NFS_CAR_FLAKE'] = value
        assert run([d / 'selection'], env=current).stdout.strip() == expected

    # Compile the actual menu row with the production registry, not a mirror row.
    port = (RT / 'settings_port.c').read_text()
    row_begin = port.index('static const char *const kFlake[]')
    row_end = port.index('};', port.index('static Setting s_flake', row_begin)) + 2
    row = port[row_begin:row_end]
    from post_port_values_test import DRIVER
    driver = DRIVER % ('settings_add(&s_flake);',
                       'printf("%d %d %d\\n",s_flake.value,s_flake.hidden,s_flake.nchoices);')
    driver = driver.replace('int main(void)',
                            'static void materials_set_car_flake(int mode){(void)mode;}\n' + row + '\nint main(void)')
    for name in ('settings.c', 'roots.h', 'bundle_roots.h'):
        (d / name).write_bytes((RT / name).read_bytes())
    (d / 'gen').mkdir()
    (d / 'gen/x360_shader_lits.inc').write_text('#define X360_SHADER_LITS 0\n')
    (d / 'gen/x360_engine.inc').write_text('#define X360_ENGINE_CONSTS 0\n')
    (d / 'menu.c').write_text(driver)
    (d / 'roots.txt').write_text('pc_root=%s\n' % d)
    run(['clang', '-Werror', '-DNFS_PUBLIC=1', '-I', RT, '-I', RT.parent / 'recomp',
         d / 'menu.c', d / 'settings.c', '-o', d / 'menu'])
    env.update(HOME=str(d / 'home'), NFS_ROOTS=str(d / 'roots.txt'))
    assert run([d / 'menu'], env=env).stdout.strip() == '2 0 3'
    env['NFS_CAR_FLAKE'] = 'generated'
    assert run([d / 'menu'], env=env).stdout.strip() == '2 0 3'
    print('paint_flake_test: no-console selector 4/4; PC-only menu default=generated, visible PASS')


