"""R28 tree shading data: writes runtime/gen/trees_params.inc, the X360 billboardshader Params of every lightmaterials
(class 0xD32A743F) collection in the X360 ATTRIBUTES.BIN that carries them.
Decoded data: X360 Function_8244F510 (billboardshader SetupMesh, vtable
82091F70, effect index 1 = "billboardshader" in the 828FBCD8 effect table) loads Params = (lfs attrib 0x483B6E25, lfs
attrib 0x42FF3188 Brightness, lfs layout+0x6C (0xCA470C4E), lfs attrib 0xE0985F58) from the mesh entry's instance
(entry+0x20, built by 8243D588 from the entry's collection key). PC builds the same instance (006E3EE0 chunk 0x134C02:
FindCollection(0xD32A743F, StringToKey(entry+0x60 name))) but its vault has no lightmaterials class, so the PC draw is
matched by its material name, and the row's key is that name's Attrib hash = the X360 collection key.
usage: trees_params.py [--check [INC]] <X360 GLOBAL dir> [OUT]   --check: re-decode the vault and compare with INC, exit 1
on any difference (default INC and OUT: runtime/gen/trees_params.inc; tools/gen_tables.py writes OUT)"""
import os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "../tools_snapshot/vaults"))
from compare_vaults import Side          # noqa: E402
from vaultlib import hash32              # noqa: E402

CLASS, K_AMBIENT, K_BRIGHT, K_LAYOUT, K_WRAP = 0xD32A743F, 0x483B6E25, 0x42FF3188, 0xCA470C4E, 0xE0985F58
K_AREF = 0xCF2D5699                      # layout+0x88 (u8): the alpha ref of 8244F680's two passes
NAMES = ["treecards", "treeleaves"]      # PC 0x134C02 material names whose hash is a Params collection (offline scan)


def decode(gdir):
    xb = Side(gdir, 'X360', '>')
    xb.parse(dict(xb.types))
    colls = {k[3]: c for k, c in xb.colls.items() if k[2] == CLASS}
    byname = {hash32(n): n for n in NAMES}

    def field(key, fk):                  # Attrib::Instance::GetAttributePointer walks the parent chain
        while key:
            c = colls.get(key)
            if not c:
                return None
            f = c['fields'].get(fk)
            if f:
                return f[2][0][1][0]
            key = c['parent']
        return None
    rows = []
    for key in sorted(colls):
        a, b, w = field(key, K_AMBIENT), field(key, K_BRIGHT), field(key, K_WRAP)
        if a is None and b is None and w is None:
            continue                     # no Params of its own or inherited: the X360 draw would read the zero default
        if key not in byname:
            sys.exit("trees_params: collection %08X has Params but no PC material name" % key)
        rows.append((byname[key], key, (a or 0.0, b or 0.0, field(key, K_LAYOUT) or 0.0, w or 0.0), field(key, K_AREF) or 0))
    return len(colls), rows


def f32(x):
    return struct.unpack('<I', struct.pack('<f', x))[0]


def emit(n, rows):
    out = ["// Generated by runtime/trees_params.py from the X360 ATTRIBUTES.BIN (lightmaterials 0xD32A743F). Do not edit.",
           "// %d lightmaterials collections, %d with billboardshader Params. {PC material name, Attrib key, Params bits, alpha ref}" % (n, len(rows)),
           "// alpha ref = layout+0x88 (0xCF2D5699, u8). Params = (ambient 0x483B6E25, Brightness 0x42FF3188, layout+0x6C, wrap 0xE0985F58), as X360 8244F510 loads them."]
    for name, key, p, aref in rows:
        out.append('{"%s", 0x%08Xu, {{0x%08Xu, 0x%08Xu, 0x%08Xu, 0x%08Xu}}, %d},   // %s, alpha ref %d' % (
            name, key, *[f32(x) for x in p], aref, ", ".join("%.9g" % x for x in p), aref))
    return "\n".join(out) + "\n"


def main():
    args = sys.argv[1:]
    check = None
    if args and args[0] == "--check":
        args = args[1:]
        check = os.path.join(HERE, "gen", "trees_params.inc")
        if args and args[0].endswith(".inc"):
            check = args.pop(0)
    gdir = args[0]
    out = args[1] if len(args) > 1 else os.path.join(HERE, "gen", "trees_params.inc")
    n, rows = decode(gdir)
    for name, key, _, _ in rows:
        assert hash32(name) == key
    text = emit(n, rows)
    if check:
        have = open(check).read()
        if have != text:
            import difflib
            sys.stdout.writelines(difflib.unified_diff(have.splitlines(True), text.splitlines(True), check, "vault"))
            print("trees_params: FAIL, %s differs from the vault" % check)
            sys.exit(1)
        print("trees_params: PASS, %d rows match the vault (%d lightmaterials collections)" % (len(rows), n))
        return
    with open(out, "w") as f:
        f.write(text)
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
