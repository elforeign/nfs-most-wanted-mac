// Included after render_post.m's common full-screen shader. No global luma gate
// is changed. p0: requested gain, Natural flag, existing chain gain, unused.
static const char *lampglow_src =
"inline float3 lamp_bright(float3 c, float4 p) {\n"
"    float l = dot(c, LUM);\n"
"    float e = max(l * p.x / (p.y + 0.001) - p.z, 0.0) * smoothstep(0.55, 0.75, l);\n"
"    return c * (e / max(l, 1e-4));\n"
"}\n"
"fragment float4 fs_lamp_source(VOut i [[stage_in]], texture2d<float> scene [[texture(0)]],\n"
"    texture2d<float> lamps [[texture(1)]], sampler sm [[sampler(0)]], constant K &k [[buffer(0)]]) {\n"
"    float4 avg = 0; float3 em = 0, delta = 0;\n"
"    // Lamps are empty almost everywhere. Natural: a tap with no lamp light adds exactly 0 (e = 0, so both delta\n"
"    // terms are the same value), so all 16 lamp taps are read first (independent fetches) and a pixel whose taps\n"
"    // are all empty returns what the loop would (em 0 -> 0) without reading the scene. Glow's avg needs every tap.\n"
"    if (k.p0.y > 0.5) {\n"
"        float3 l[16]; float lsum = 0;\n"
"        for (int n = 0; n < 16; ++n) { l[n] = lamps.sample(sm, i.uv + k.off[n].xy, level(0)).rgb; lsum += l[n].x + l[n].y + l[n].z; }\n"
"        if (lsum == 0.0) return float4(0, 0, 0, 1);\n"
"        for (int n = 0; n < 16; ++n) {\n"
"            float4 s = scene.sample(sm, i.uv + k.off[n].xy); float3 e = min(l[n], s.rgb);\n"
"            em += e; delta += s.rgb * gw(s.rgb) - max(s.rgb - e, 0.0) * gw(max(s.rgb - e, 0.0));\n"
"        }\n"
"        em *= 0.0625; delta *= 0.0625;\n"
"        return float4(max(em * k.p0.x - max(delta, 0.0) * k.p0.z, 0.0), 1);\n"
"    }\n"
"    for (int n = 0; n < 16; ++n) {\n"
"        float2 uv = i.uv + k.off[n].xy; float4 s = scene.sample(sm, uv);\n"
"        float3 e = min(lamps.sample(sm, uv).rgb, s.rgb);\n"
"        avg += s; em += e;\n"
"    }\n"
"    avg *= 0.0625; em *= 0.0625; delta *= 0.0625;\n"
"    if (k.p0.y < 0.5) {\n"
"        float m = k.wgt[0].w > 1.5 ? 1.0 : mix(1.0 - avg.a, avg.a, k.wgt[0].w);\n"
"        delta = lamp_bright(avg.rgb * m, k.wgt[0]) - lamp_bright(max(avg.rgb - em, 0.0) * m, k.wgt[0]);\n"
"    }\n"
"    // Total requested energy is bounded by gain * captured emission. Credit\n"
"    // existing bloom before adding the remainder, including its kernel gain.\n"
"    return float4(max(em * k.p0.x - max(delta, 0.0) * k.p0.z, 0.0), 1);\n"
"}\n";
