#!/usr/bin/env python3
"""Authored sea and harbour wave sets for the port's water shader; no game inputs.

JONSWAP (Hasselmann et al. 1973, section 2.4): X=gF/U10^2, alpha=.076 X^-.22,
fp=3.5 (g/U10) X^-.33, S(f)=alpha g^2 (2pi)^-4 f^-5 exp(-1.25 (fp/f)^4) gamma^q,
q=exp(-(f-fp)^2/(2 sigma^2 fp^2)), gamma=3.3, sigma .07 below / .09 above the peak;
g=9.80665 m/s^2 (CODATA standard gravity). Deep-water dispersion omega=sqrt(g|k|).
Authored choices: the two scenarios (harbour 4 m/s over 500 m, coast 6 m/s over
10 km), eight logarithmic bands per layer (layer 0 tiles 128 m and covers
wavelengths 2-128 m, layer 1 tiles 16 m and covers .25-2 m), cos^2 spreading
about one wind direction, seed 0, and the shader's reflection offset.
Below the shortest band the slope variance is Cox and Munk's clean-surface
total 0.003 + 5.12e-3 U (J. Opt. Soc. Am. 44, 838, 1954) minus what the bands hold;
the shader widens its sun lobe by it. Each band keeps its height energy (A=sqrt(2 m0)) and slope energy (f=(m4/m0)^.25);
its wavevector is snapped to 2pi n/L so every layer tiles exactly.
"""
import argparse
import math
from pathlib import Path
import random

G = 9.80665
GAMMA = 3.3
IOR = 1.333                              # air/water (PBRT dielectric reflection)
F0 = ((IOR - 1) / (IOR + 1)) ** 2        # 0.020373
LAYERS = ((128.0, 2.0, 128.0), (16.0, 0.25, 2.0))   # tile m, shortest and longest wavelength m
BANDS = 8
WIND = 0.6                               # rad from +x: one fixed wind direction
DISTORT = 0.25                           # reflection lookup offset per unit slope (screen fraction)
SCENARIOS = {"HARBOUR": (4.0, 500.0), "COAST": (6.0, 10000.0)}


def spectrum(u10, fetch):
    x = G * fetch / u10 ** 2
    alpha, fp = 0.076 * x ** -0.22, 3.5 * (G / u10) * x ** -0.33

    def s(f):
        sigma = 0.07 if f <= fp else 0.09
        q = math.exp(-(f - fp) ** 2 / (2 * sigma * sigma * fp * fp))
        return alpha * G * G * (2 * math.pi) ** -4 * f ** -5 * math.exp(-1.25 * (fp / f) ** 4) * GAMMA ** q
    return s, fp


def freq(wavelength):
    return math.sqrt(G * 2 * math.pi / wavelength) / (2 * math.pi)


def moments(s, f0, f1, steps=4000):
    """Midpoint m0 and m4 over [f0, f1] on a log grid."""
    m0 = m4 = 0.0
    r = math.log(f1 / f0)
    for i in range(steps):
        a, b = f0 * math.exp(r * i / steps), f0 * math.exp(r * (i + 1) / steps)
        f = math.sqrt(a * b)
        v = s(f) * (b - a)
        m0 += v
        m4 += v * f ** 4
    return m0, m4


def spread(rng):
    """Forward-facing cos^2 spreading about WIND, by rejection."""
    while True:
        t = (rng.random() - 0.5) * math.pi
        if rng.random() <= math.cos(t) ** 2:
            return WIND + t


def waves(u10, fetch):
    """Per layer: (kx, ky, amplitude, phase) for each band, k snapped to the layer's tile."""
    s, _ = spectrum(u10, fetch)
    rng = random.Random(0)
    result = []
    for tile, short, long in LAYERS:
        layer = []
        for b in range(BANDS):
            l1 = long * (short / long) ** (b / BANDS)
            l0 = long * (short / long) ** ((b + 1) / BANDS)
            m0, m4 = moments(s, freq(l1), freq(l0))
            f = (m4 / m0) ** 0.25 if m0 > 0 else freq(math.sqrt(l0 * l1))
            k = (2 * math.pi * f) ** 2 / G
            th = spread(rng)
            nx, ny = round(k * math.cos(th) * tile / (2 * math.pi)), round(k * math.sin(th) * tile / (2 * math.pi))
            if nx == 0 and ny == 0:
                nx = 1
            layer.append((2 * math.pi * nx / tile, 2 * math.pi * ny / tile, math.sqrt(2 * m0), rng.random() * 2 * math.pi))
        result.append(layer)
    return result


def slope(x, y, t, layers):
    """Analytic surface slope (dh/dx, dh/dy) of h = sum A cos(k.x - omega t + phase)."""
    sx = sy = 0.0
    for layer in layers:
        for kx, ky, a, p in layer:
            w = math.sqrt(G * math.hypot(kx, ky))
            d = -a * math.sin(kx * x + ky * y - w * t + p)
            sx += d * kx
            sy += d * ky
    return sx, sy


def floor_variance(u10, layers):
    """Cox-Munk total mean-square slope minus the bands' own (snapped) slope variance."""
    modelled = sum(0.5 * (a * math.hypot(kx, ky)) ** 2 for layer in layers for kx, ky, a, _ in layer)
    return max(0.003 + 5.12e-3 * u10 - modelled, 0.0)


def header():
    out = ['// Generated by tools_snapshot/port_water_gen.py; authored, no game inputs.\n',
           '#define PORTW_F0 "%.6f"\n' % F0, '#define PORTW_IOR "%.3f"\n' % IOR, '#define PORTW_G "%.5f"\n' % G,
           '#define PORTW_DISTORT "%.3f"\n' % DISTORT, '#define PORTW_WAVES %d\n' % (BANDS * len(LAYERS))]
    for name, (u10, fetch) in SCENARIOS.items():
        layers = waves(u10, fetch)
        flat = [w for layer in layers for w in layer]
        out.append('#define PORTW_%s_FLOOR "%.6f"\n' % (name, floor_variance(u10, layers)))
        out.append('#define PORTW_%s "' % name + ', '.join(
            'float4(%.8ef, %.8ef, %.8ef, %.8ef)' % (kx, ky, a if a > 1e-30 else 0.0, p) for kx, ky, a, p in flat) + '"\n')
    return ''.join(out)


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out', type=Path, required=True)
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(header())
