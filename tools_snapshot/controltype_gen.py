#!/usr/bin/env python3
"""Generates runtime/gen/controltype_buttons.inc: the X360 Control Types 2-5 button presets controltype.c applies
(ct_buttons), decoded from the player's X360 ATTRIBUTES.BIN. Type n's drive collection is the key at index
leftStick + 2 * variant of the PC exe's selector table 0089F6AC (the same keys as the X360's); each action's record names
the pad control (parents resolved) and, for an analog control other than the left stick, its ramp low.
usage: python -I tools_snapshot/controltype_gen.py <X360 GLOBAL dir> <PC speed.exe> <out .inc>   (tools/gen_tables.py)
Without an X360 copy gen_tables writes an empty preset table: every type keeps the player's buttons."""
import os, struct, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, 'vaults'))
import compare_vaults as cv   # noqa: E402
from vaultlib import hash32   # noqa: E402

# controltype.c's order of the ten actions a preset moves, with the X360 GameAction names.
ACTIONS = [('CT_GAS', 'GAMEACTION_GAS'), ('CT_BRAKE', 'GAMEACTION_BRAKE'), ('CT_HANDBRAKE', 'GAMEACTION_HANDBRAKE'),
           ('CT_NOS', 'GAMEACTION_NOS'), ('CT_GAMEBREAKER', 'GAMEACTION_GAMEBREAKER'),
           ('CT_SHIFTUP', 'GAMEACTION_SHIFTUP'), ('CT_SHIFTDOWN', 'GAMEACTION_SHIFTDOWN'),
           ('CT_CAMERA', 'CAMERAACTION_CHANGE'), ('CT_LOOKBACK', 'CAMERAACTION_LOOKBACK'), ('CT_RESET', 'GAMEACTION_RESET')]
ANALOG = {'ARY_U', 'ARY_D', 'L', 'R'}
SELECTOR = 0x0089F6AC


def exe_u32(exe, va):
    b = open(exe, 'rb').read()
    pe = struct.unpack_from('<I', b, 0x3c)[0]
    ns, osz = struct.unpack_from('<H', b, pe + 6)[0], struct.unpack_from('<H', b, pe + 20)[0]
    base = struct.unpack_from('<I', b, pe + 52)[0]
    for i in range(ns):
        _, vs, va_, rs, ro = struct.unpack_from('<8sIIII', b, pe + 24 + osz + 40 * i)
        if va_ <= va - base < va_ + max(vs, rs):
            return struct.unpack_from('<I', b, ro + va - base - va_)[0]
    raise ValueError('address %08X not in the exe' % va)


def x360_records(gdir):
    xb = cv.Side(gdir, 'X360', '>')
    xb.parse(dict(xb.types))
    C = {k: c for (f, v, cls, k), c in xb.colls.items() if f == 'ATTRIBUTES.BIN'}

    def get(key, action):
        while key in C:
            f = C[key]['fields'].get(hash32(action))
            if f:
                w = f[2][0][1]
                raw = b''.join(x[1] if x[0] == 'r' else b'\0\0\0\0' for x in w)
                lo, = struct.unpack_from('>f', raw, 20)
                return (w[3][1] if w[3][0] == 'p' else None), round(lo, 3)
            key = C[key]['parent']
        return None, 0
    return get


def main():
    gdir, exe, out = sys.argv[1:4]
    get = x360_records(gdir)
    lines = ['// Generated by tools_snapshot/controltype_gen.py from the X360 ATTRIBUTES.BIN. Do not edit.',
             '// Variants 2-5 (X360 drive2..drive5): {action, pad control, ramp low}.']
    for variant in range(1, 5):
        key = exe_u32(exe, SELECTOR + 4 * (1 + 2 * variant))
        row = []
        for c, name in ACTIONS:
            src, lo = get(key, name)
            if not src:
                raise ValueError('drive key %08X: no source for %s' % (key, name))
            row.append('{%s, "%s", %s}' % (c, src, ('%.3gf' % lo) if src in ANALOG and lo else '0'))
        lines.append('    {' + ', '.join(row) + '},')
    open(out, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
