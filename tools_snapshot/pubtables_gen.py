# stmw, FPR loads without update, FP arithmetic. Any other instruction is treated as writing both its rD and rA fields.
NO_GPR_WRITE = {3, 10, 11, 16, 18, 19, 36, 38, 44, 47, 48, 50, 52, 54, 59, 63}
VOLATILE = (0,) + tuple(range(3, 13))       # GPRs a call may change


def load_address(img, site):
    """The address the `lfs` at `site` loads from: its displacement added to the value its base register holds, found by
    following `lis`/`addi` forward through the instructions before it (a window of 0x900 bytes; a register set by anything
    else is unknown). SystemExit if the word is not an lfs or its base register is unknown."""
    word = lambda a: struct.unpack_from(">I", img, a - IMAGE_BASE)[0]
    sx = lambda v: struct.unpack(">h", struct.pack(">H", v & 0xFFFF))[0]
    w = word(site)
    if w >> 26 != 48:
        raise SystemExit("pubtables_gen: %08X is not an lfs (%08X): refused" % (site, w))
    regs = {}
    for a in range(max(IMAGE_BASE, site - 0x900), site, 4):
        v = word(a)
        op, rd, ra = v >> 26, (v >> 21) & 31, (v >> 16) & 31
        if op == 15 and ra == 0:
            regs[rd] = (v & 0xFFFF) << 16
        elif op == 14:
            if ra == 0:
                regs[rd] = sx(v) & 0xFFFFFFFF
            elif ra in regs:
                regs[rd] = (regs[ra] + sx(v)) & 0xFFFFFFFF
            else:
                regs.pop(rd, None)
        elif op in NO_GPR_WRITE:
            if op in (16, 18, 19) and v & 1:     # bl / bcl / bclrl / bcctrl: the callee may change the volatile GPRs
                for r in VOLATILE:
                    regs.pop(r, None)
        elif op in (17, 46) or (op == 31 and (v >> 1) & 0x3FF in (533, 597)):   # sc: all; lmw: rD..r31; lsw*: all
            for r in (range(rd, 32) if op == 46 else range(32)):
                regs.pop(r, None)
        else:                                # addis rA!=0, ori, rlwinm, loads, update forms, X-form ops ...: rD and rA
            regs.pop(rd, None)
            regs.pop(ra, None)
    base = (w >> 16) & 31
    if base not in regs:
        raise SystemExit("pubtables_gen: the base register of the lfs at %08X is not a known constant: refused" % site)
    return (regs[base] + sx(w)) & 0xFFFFFFFF


def f32_text(v):
    """A float32 as a C float literal, shortest round-trip ("0.0090909088f" stays exact, "4.0f")."""
    if v == int(v) and abs(v) < 1e7:
        return "%d.0f" % v
    for n in range(1, 10):
        t = "%.*g" % (n, v)
        if struct.unpack("<f", struct.pack("<f", float(t)))[0] == v:
            return t + "f"
    return "%.9gf" % v


def engine_text(img, source, sites=None):
    out = [HDR % source + "#define X360_ENGINE_CONSTS 1"]
    for name, va in ENGINE + ENGINE_DEC:       # a constant's address must be what its guest load instruction addresses
        site = (LOAD_SITES if sites is None else sites).get(name)
        if site and load_address(img, site) != va:
            raise SystemExit("pubtables_gen: %s at %08X is not what the load at %08X reads (%08X): refused" %
                             (name, va, site, load_address(img, site)))
    for name, va in ENGINE_DEC:
        v = struct.unpack_from(">f", img, va - IMAGE_BASE)[0]
        if not math.isfinite(v) or not 0.0 < v < 100.0:
            raise SystemExit("pubtables_gen: %s at %08X is not a plausible number (%r): refused" % (name, va, v))
        out.append("#define %s %s" % (name, f32_text(v)[:-1]))
    for name, va in ENGINE:
        v = struct.unpack_from(">f", img, va - IMAGE_BASE)[0]
        if not math.isfinite(v):
            raise SystemExit("pubtables_gen: %s at %08X is not a finite number (%r): refused" % (name, va, v))
        out.append("#define %s %s" % (name, f32_text(v)))
    for name, va in ENGINE_LI:
        w = struct.unpack_from(">I", img, va - IMAGE_BASE)[0]
        if w >> 26 != 14 or (w >> 16) & 0x1F:
            raise SystemExit("pubtables_gen: %08X is not an li instruction (%08X): refused" % (va, w))
        out.append("#define %s %d" % (name, struct.unpack(">h", struct.pack(">H", w & 0xFFFF))[0]))
    return "\n".join(out) + "\n"


STEER_KEY, STEER_CLS = 0xAD37E45A, 0x2DEE1998        # controller drive_analog (Type 1) collection
STEER_FIELDS = (0x37B1B6A8, 0xB3A37C41)               # the two continuous steering arrays
STEER_LOW_OFFSET = 8 + 0x14                           # array header + record offset of the low


def steer_low_word(x360_attrib):
    """The X360 steering dead zone (the ramp's low) as a float32 word, read from the player's ATTRIBUTES.BIN: both
    steering fields must agree, and be a fraction in (0, 0.5)."""
    from vaultlib import Vault, read_vpak
    lows = set()
    for name, b, v, bo, vo in read_vpak(x360_attrib):
        vault = Vault(name, b, v, ">", bo, vo)
        for _, typ, _, off in vault.exports:
            if typ == 0x8E112EB7 and vault.u32(v, off) == STEER_KEY and vault.u32(v, off + 4) == STEER_CLS:
                n, nt = struct.unpack_from(">II", v, off + 0x14)
                for i in range(n):
                    entry = off + 0x20 + 4 * nt + 12 * i
                    if vault.u32(v, entry) in STEER_FIELDS:
                        dep, at = vault.deref(0, entry + 4)
                        raw = vault.bufs[dep][at + STEER_LOW_OFFSET:at + STEER_LOW_OFFSET + 4]
                        lows.add(struct.unpack(">I", raw)[0])
    if len(lows) != 1:
        raise SystemExit("pubtables_gen: no consistent steering dead zone in %s (%d values)" % (x360_attrib, len(lows)))
    word = lows.pop()
    if not 0 < struct.unpack(">f", struct.pack(">I", word))[0] < 0.5:
        raise SystemExit("pubtables_gen: the steering dead zone in %s is not a fraction" % x360_attrib)
    return word


def steer_text(word):
    return "#define X360E_STEER_LOW_WORD 0x%08Xu\n" % word


def engine_consts(xex, work):
    exe = work / "xex_read"
    if not exe.exists():
        subprocess.run(["clang", "-O2", "-w", "-o", str(exe), str(HERE / "xex_read.c")], check=True)
    r = subprocess.run([str(exe), str(xex), "0x%X" % IMAGE_BASE, str(IMAGE_SIZE), "0x%08X" % XEX_TITLE,
                        XEX_IMAGE_SHA256], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=False)
    if r.returncode or len(r.stdout) != IMAGE_SIZE:
        raise SystemExit("pubtables_gen: %s is not the supported NFS:MW X360 executable: %s" %
                         (xex, r.stderr.decode(errors="replace").strip()))
    return engine_text(r.stdout, "X360 default.xex (engine constants)")


ENGINE_STUB = (NO_X360 % "executable" + "#define X360_ENGINE_CONSTS 0\n" +
               "".join("#define %s %s\n" % (name, FALLBACK.get(name, "0.0f")) for name, _ in ENGINE + ENGINE_DEC) +
               "".join("#define %s 0\n" % name for name, _ in ENGINE_LI))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pc", type=Path)
    ap.add_argument("--x360", type=Path)
    ap.add_argument("--xex", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--work", type=Path)
    ap.add_argument("--engine-image", type=Path)
    a = ap.parse_args()
    if a.engine_image:                     # test hook: the engine table from a raw decoded image (no xex identity)
        (a.out / "x360_engine.inc").write_text(engine_text(a.engine_image.read_bytes(), "decoded image (test)"))
        return
    if not a.pc:
        ap.error("--pc is required")
    work = a.work or a.out
    work.mkdir(parents=True, exist_ok=True)
    pc_look = looks(find(a.pc / "GLOBAL", "ATTRIBUTES.BIN"), 0x43350, "<")
    files = {
        "padprompts_l1.inc": padprompts_l1(a.pc),
        "look_pc.inc": look_text("LOOK_PC", pc_look, "GLOBAL/attributes.bin (visuallook)"),
        "car_shadow_off.inc": car_shadow_off(a.pc),
        "pc_shader_lits.inc": pc_shader_lits(a.pc),
    }
    if a.x360:
        files["look_x360.inc"] = look_text("LOOK_X360", looks(a.x360 / "GLOBAL/ATTRIBUTES.BIN", 0x52C80, ">"),
                                           "X360 GLOBAL/ATTRIBUTES.BIN (visuallook)")
        files["glass_x360.inc"] = glass_x360(a.x360)
        files["grass_x360.inc"] = grass_x360(a.x360)
    else:
        files["look_x360.inc"] = (NO_X360 % "copy" + "// The PC records: blending to them leaves the look unchanged.\n" +
                                  look_text("LOOK_X360", pc_look, "GLOBAL/attributes.bin").split("\n", 1)[1])
        files["glass_x360.inc"] = NO_X360 % "copy" + "static const GlassX360 glass_x360[1];\n#define GLASS_X360_COUNT 0\n"
        files["grass_x360.inc"] = NO_X360 % "copy"
    if a.xex and a.xex.exists():
        files["callout_labels.inc"] = callout_labels(a.xex, work)
        files["x360_engine.inc"] = engine_consts(a.xex, work)
    else:
        files["x360_engine.inc"] = ENGINE_STUB
        files["callout_labels.inc"] = (NO_X360 % "executable" + "// Zero labels: the diagram's callouts stay hidden.\n"
                                       "static const uint32_t callout_labels[17 * 5];\n")
    files["x360_engine.inc"] += steer_text(steer_low_word(a.x360 / "GLOBAL/ATTRIBUTES.BIN") if a.x360 else 0)
    for name, text in files.items():
        (a.out / name).write_text(text)
    print("pubtables_gen: wrote %s" % " ".join(sorted(files)))


if __name__ == "__main__":
    main()
