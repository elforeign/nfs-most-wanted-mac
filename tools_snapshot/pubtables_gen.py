def ff(v):
    """A float32 as C source: 9 significant digits, always with a point (as the replaced literals were written)."""
    s = "%.9g" % v
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def gff(v):
    """Float text rounded to 6 significant digits ("%g"), spelled as the MSL taps were written (e-05 values positional:
    -0.00005, e-06 ones not: -4e-06), so the shader source and with it Metal's compiled-shader cache key stay the same."""
    s = "%g" % v
    return ("%.10f" % v).rstrip("0") if "e-05" in s else s


def gf(v):
    """A float32 rounded to 6 significant digits as C source: the glass records hold values like 0.300000042 that the
    table this replaces wrote as 0.3f (the rounded value is what the runtime has always used)."""
    s = gff(v)
    return s + (".0f" if "e" not in s and "." not in s else "f")


def find(d, name):
    p = d / name
    if p.exists():
        return p
    for q in d.iterdir():
        if q.name.lower() == name.lower():
            return q
    return p


def bun_chunks(data, want):
    """Every chunk with id `want` in a BUN (little-endian chunk headers on both platforms)."""
    out = []

    def walk(o, end):
        while o + 8 <= end:
            cid, sz = struct.unpack_from("<II", data, o)
            if cid == want:
                out.append(data[o + 8:o + 8 + sz])
            elif cid & 0x80000000:
                walk(o + 8, o + 8 + sz)
            o += 8 + sz
    walk(0, len(data))
    return out


# ---- PC ----
def padprompts_l1(pc):
    d = find(pc / "GLOBAL", "GLOBALB.BUN").read_bytes()
    o = 0
    while True:
        o = d.find(b"L1\0", o)
        if o < 0:
            raise SystemExit("pubtables_gen: no L1 TextureInfo in GLOBALB.BUN")
        r = o - 0x0C
        if r >= 0 and d[r + 0x28:r + 0x2C] == bytes.fromhex("CF931A00") and not any(d[r:r + 0x0C]):
            break
        o += 1
    rec = bytearray(d[r:r + 124])
    rec[0x0C:0x28] = bytes(0x1C)        # name, hash: the runtime writes the glyph's
    rec[0x38:0x48] = bytes(0x10)        # data placement and size, image size: the runtime's
    return HDR % "GLOBAL/GLOBALB.BUN (TextureInfo L1)" + \
        "static const uint8_t l1[124] = {%s};\n" % ", ".join("0x%02X" % b for b in rec)


LOOK_COUNT, LOOK_SIZE = 5, 0xE0


def looks(path, base, e):
    d = path.read_bytes()
    rows = []
    for i in range(LOOK_COUNT):
        o = base + LOOK_SIZE * i
        f = lambda off: struct.unpack_from(e + "f", d, o + off)[0]
        rows.append([f(0xC0), f(0xC4), f(0xC8), f(0xD0), f(0xD4), f(0xDC)] +
                    [f(0x40 + 16 * k + 4) for k in range(4)] + [f(0x80 + 16 * k + 4) for k in range(4)])
    for r in rows:   # a sanity check of the record layout: tints in 0..2, curve end points 1
        if not all(0 <= v <= 2 for v in r[:3]) or r[9] != 1.0:
            raise SystemExit("pubtables_gen: %s has no visuallook records at 0x%X" % (path, base))
    return rows


def look_text(name, rows, what):
    return HDR % what + "static const float %s[5][14] = {\n%s};\n" % (
        name, "".join("    {%s},\n" % ", ".join(ff(v) for v in r) for r in rows))


SHADOW_ORDER = [2, 1] + list(range(3, 17))   # the PC PS's tap order (tn_car_p0_ps_2_*: c2 first)


def car_shadow_off(pc):
    d = (pc / "speed.exe").read_bytes()
    o = 0
    while True:
        o = d.find(struct.pack("<I", 0x05000051), o)
        if o < 0:
            raise SystemExit("pubtables_gen: no 16-tap shadow constants in speed.exe")
        regs = {}
        for k in range(16):
            p = o + 24 * k
            tok, reg = struct.unpack_from("<II", d, p)
            if tok != 0x05000051:
                break
            regs[reg & 0x7FF] = struct.unpack_from("<4f", d, p + 8)
        if sorted(regs) == list(range(1, 17)):
            break
        o += 4
    taps = ["float2(%sf, %sf)" % (gff(regs[c][0]), gff(regs[c][1])) for c in SHADOW_ORDER]
    lines = ["    const float2 off[16] = { " + ", ".join(taps[:3]) + ","]
    for k in range(3, 15, 4):
        lines.append("        " + ", ".join(taps[k:k + 4]) + ",")
    lines.append("        " + taps[15] + " };")
    return HDR % "speed.exe (car PS shadow taps)" + "#define CAR_SHADOW_OFF16 \\\n%s\n" % " \\\n".join(
        '"%s\\n"' % ln for ln in lines)


# PC pixel shaders in speed.exe, each found by FNV-1a 64 of its ps_2_0 tokens with the def values zeroed (the program, not
# its numbers), and the def components the port's Metal code uses: (macro, shader, register, component, transform).
PC_SHADERS = {"particles t2": 0x26521F86C686ED79, "particles t1": 0x05DC14BC2F6E8AF4, "car t1": 0xFD9C153D0D8C52EC}
PC_DEFS = [
    ("PCS_PARTICLE_FLOOR", "particles t2", 0, 2, None),          # shadowed: floor + (1 - floor) x lit
    ("PCS_PARTICLE_LIT", "particles t2", 0, 2, "one_minus"),
    ("PCS_PARTICLE_HW_BIAS", "particles t1", 0, 0, None),        # hardware-shadow path: saturate(lit + this)
    ("PCS_CAR_SHADOW_FLOOR", "car t1", 1, 2, None),              # car paint: mix(floor + InvShadowStrength, 1, lit)
]


def shortest(v):
    """A float32 as its shortest round-tripping text ("0.3", "0.7", "0.5")."""
    for n in range(1, 10):
        s = "%.*g" % (n, v)
        if struct.unpack("<f", struct.pack("<f", float(s)))[0] == v:
            return s
    return "%.9g" % v


def pc_programs(d):
    """{FNV of the zeroed program: {register: 4 floats}} for every ps_2_0 program in speed.exe."""
    end, out = struct.pack("<I", 0x0000FFFF), {}
    o = d.find(b"\x00\x02\xff\xff")          # ps_2_0 version token
    while o >= 0:
        e = d.find(end, o)
        while e >= 0 and (e - o) % 4:
            e = d.find(end, e + 1)
        if o % 4 == 0 and 0 < e - o < 0x8000:
            toks, p, defs = bytearray(d[o:e + 4]), 4, {}
            while p < len(toks) - 4:
                t = struct.unpack_from("<I", toks, p)[0]
                if t & 0xFFFF == 0x51 and p + 24 <= len(toks):
                    defs[struct.unpack_from("<I", toks, p + 4)[0] & 0x7FF] = struct.unpack_from("<4f", toks, p + 8)
                    toks[p + 8:p + 24] = bytes(16)
                p += 4 + (((t >> 16) & 0x7FFF) if t & 0xFFFF == 0xFFFE else (t >> 24) & 0xF) * 4
            h = 1469598103934665603
            for b in toks:
                h = ((h ^ b) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
            out.setdefault(h, defs)
        o = d.find(b"\x00\x02\xff\xff", o + 4)
    return out


def pc_shader_lits(pc):
    progs = pc_programs((pc / "speed.exe").read_bytes())
    out = [(HDR % "speed.exe (car and particles PS defs)").rstrip("\n")]
    for macro, shader, reg, comp, how in PC_DEFS:
        defs = progs.get(PC_SHADERS[shader])
        if not defs or reg not in defs:
            raise SystemExit("pubtables_gen: the %s pixel shader (def c%d) is not in speed.exe" % (shader, reg))
        v = defs[reg][comp]
        if how == "one_minus":
            v = struct.unpack("<f", struct.pack("<f", 1.0 - v))[0]
        if not math.isfinite(v):
            raise SystemExit("pubtables_gen: %s def c%d is not a finite number: refused" % (shader, reg))
        out.append('#define %s "%s"' % (macro, shortest(v)))
    return "\n".join(out) + "\n"


