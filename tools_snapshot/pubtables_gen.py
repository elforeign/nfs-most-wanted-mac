GLASS = ["WINDOWMASK", "WINDSHIELD", "*WINDSHIELD_TINT_", "HEADLIGHTGLASS", "CLEARPLASTIC", "MOLDINGS"]


def glass_x360(x360):
    d = (x360 / "GLOBAL/GLOBALB.BUN").read_bytes()
    mats = {}
    for b in bun_chunks(d, 0x00135200):
        mats[b[0x14:0x34].split(b"\0")[0].decode("latin1")] = b
    names = []
    for g in GLASS:
        names += sorted(n for n in mats if n.startswith(g[1:])) if g[0] == "*" else [g]
    out = [HDR % "X360 GLOBAL/GLOBALB.BUN (light materials)",
           "static const GlassX360 glass_x360[] = {\n"]
    for n in names:
        b = mats[n]
        h, = struct.unpack_from("<I", b, 0xC)
        f = lambda off: struct.unpack_from("<f", b, off)[0]
        out.append("    {0x%08Xu, %s, %s, %s, %s},   // %s\n" % (h, gf(f(0x50)), gf(f(0x54)), gf(f(0x80)), gf(f(0x90)), n))
    out.append("};\n#define GLASS_X360_COUNT %d\n" % len(names))
    return "".join(out)


