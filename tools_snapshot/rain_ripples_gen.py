#!/usr/bin/env python3
"""Bake authored effect channels for the wet-road shader; no game inputs.

Marshall-Palmer n(D)=8000 exp(-4.1 I^-.21 D), D in mm; collect n*v,
normalize its volume flux to I=10 mm/h (AMT 14:7681, 2021). Fall speed:
4.323(D-.03) below .6 mm, otherwise 9.65-10.3 exp(-.6D) m/s
(AMT 17:6933, 2024). Gravity-capillary dispersion and bulk/bottom damping
follow Fluids 7(4):137, equations 19 and 55-56. The reference film, wavelength,
packet, amplitude coupling and channel gains below are authored choices.
"""
import argparse
import importlib.util
import math
from pathlib import Path
import random

SIZE, FRAMES, TILE = 128, 16, 0.5
FILM, WAVELENGTH, NU = .001, .020, 1e-6
K = 2 * math.pi / WAVELENGTH
OMEGA = math.sqrt((9.81*K + .072*K**3/1000) * math.tanh(K*FILM))
GROUP = ((9.81 + 3*.072*K*K/1000)*math.tanh(K*FILM) +
         (9.81*K + .072*K**3/1000)*FILM/math.cosh(K*FILM)**2)/(2*OMEGA)
BETA = 2*NU*K*K + math.sqrt(NU*OMEGA/2)*K/math.sinh(2*K*FILM)
PERIOD = 2/BETA                 # two amplitude damping times, smooth cutoff
SCALE2 = math.sqrt(2)


def speed(d):
    return 4.323*(d-.03) if d < .6 else 9.65-10.3*math.exp(-.6*d)


def events():
    """Midpoint quadrature; impact-count CDF, volume-normalized flux; seed 0."""
    step = .001
    diameters = [.03 + (i+.5)*step for i in range(5970)]
    weights = [8000*math.exp(-4.1*10**(-.21)*d)*speed(d)*step for d in diameters]
    volume = sum(w*math.pi/6*(d*.001)**3 for d, w in zip(diameters, weights))
    flux = sum(weights) * (10*.001/3600)/volume
    mean = flux*TILE*TILE*PERIOD/(1+SCALE2*SCALE2)
    rng = random.Random(0)
    p, n = 1., -1
    while p > math.exp(-mean):
        p *= rng.random()
        n += 1
    cdf, total = [], 0.
    for weight in weights:
        total += weight
        cdf.append(total)
    import bisect
    result = []
    for _ in range(n):
        d = diameters[bisect.bisect_left(cdf, rng.random()*total)]
        # 20 um for a 2 mm drop, momentum scaling, linear-film cap 50 um.
        amplitude = min(FILM/20, FILM/50 * d**3*speed(d)/(8*speed(2)))
        result.append((rng.random()*TILE, rng.random()*TILE, rng.random()*PERIOD, d*.001/2, amplitude))
    return result


def gradient(x, y, t, drops):
    hx = hy = 0.
    for ex, ey, birth, core, amplitude in drops:
        age = (t-birth) % PERIOD
        dx, dy = (x-ex+TILE/2) % TILE-TILE/2, (y-ey+TILE/2) % TILE-TILE/2
        r = math.sqrt(dx*dx+dy*dy+core*core)
        z = (r-GROUP*age)/(2*WAVELENGTH)
        if abs(z) >= 1:
            continue
        envelope = (1-math.exp(-(age/(PERIOD/FRAMES))**2))*math.exp(-BETA*age)*(1-(age/PERIOD)**2)**2
        packet = (1-z*z)**3
        phase = K*r-OMEGA*age
        spread = math.sqrt(1+r/WAVELENGTH)
        derivative = amplitude*envelope/spread * (
            (-3*z*(1-z*z)**2/WAVELENGTH - packet/(2*(WAVELENGTH+r)))*math.cos(phase)
            - packet*K*math.sin(phase))
        hx += derivative*dx/r
        hy += derivative*dy/r
    return hx, hy


def frames():
    drops = events()
    # Stamp compact packet supports, avoiding a full event scan at every texel.
    result = bytearray()
    for frame in range(FRAMES):
        hx, hy = [0.]*(SIZE*SIZE), [0.]*(SIZE*SIZE)
        for drop in drops:
            ex, ey, birth, core, amplitude = drop
            age = (frame*PERIOD/FRAMES-birth) % PERIOD
            radius = GROUP*age+2*WAVELENGTH
            for iy in range(math.floor((ey-radius)*SIZE/TILE), math.ceil((ey+radius)*SIZE/TILE)):
                y = (iy+.5)*TILE/SIZE
                for ix in range(math.floor((ex-radius)*SIZE/TILE), math.ceil((ex+radius)*SIZE/TILE)):
                    x = (ix+.5)*TILE/SIZE
                    gx, gy = gradient(x, y, frame*PERIOD/FRAMES, [drop])
                    i = (iy % SIZE)*SIZE + ix % SIZE
                    hx[i] += gx
                    hy[i] += gy
        for x, y in zip(hx, hy):
            q = max(-1., min(1., (x+y)/(math.sqrt(2)*.02)))
            result.extend((round(8*min(math.hypot(x, y)/.02, 1)), round(255*max(q, 0)), round(255*max(-q, 0)), 255))
    return bytes(result)


def constants():
    """Separate PORT macros: a partial console install must never mix providers."""
    def module(name):
        spec = importlib.util.spec_from_file_location(name, Path(__file__).with_name(name+'.py'))
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        return m
    scalars = module('x360_shader_lits').RIPPLE_SCALARS
    engine = module('pubtables_gen').RIPPLE_FALLBACK
    return ''.join('#define %s "%s"\n' % (k.replace('X360S_', 'PORTS_'), v) for k, v in scalars.items()) + ''.join(
        '#define %s %s\n' % (k.replace('X360E_', 'PORTE_'), v) for k, v in engine.items())


def header(data):
    return ('// Generated by tools_snapshot/rain_ripples_gen.py; authored, no game inputs.\n' + constants() +
            'static const unsigned char port_ripple_rgba[16][128*128*4] = {\n' +
            ''.join('{' + ',\n'.join(','.join(map(str, data[f*65536+i:f*65536+i+64])) for i in range(0, 65536, 64)) + '},\n' for f in range(16)) + '};\n')


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out', type=Path, required=True)
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(header(frames()))
