#!/usr/bin/env python3
"""Generates runtime/x360audio_attrib.inc: the X360 scalar values of the sound attributes.
Each record is one scalar layout field whose value differs between the PC and X360 ATTRIBUTES.BIN, for the listed
{class: fields}: {class hash, collection key, byte offset in the collection's layout block, length, little-endian bytes}.
Run (tools/gen_tables.py does): python -I tools_snapshot/x360audio_attrib.py <X360 GLOBAL dir> <PC GLOBAL dir> [out .inc, default runtime/gen/]
Reads the game data only. Used by runtime/x360audio.c (behind NFS_X360_AUDIO)."""
import os, struct, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, 'vaults'))
import compare_vaults as cv
from vaultlib import hash32

XBG, PCG = sys.argv[1:3]
OUT = sys.argv[3] if len(sys.argv) > 3 else os.path.join(HERE, '..', 'runtime', 'gen', 'x360audio_attrib.inc')
# class -> fields (None: every scalar field that differs)
WANT = {'engineaudio': None, 'pvehicle': ['HornType', 'TrafficEngType']}
# pvehicle HornType/TrafficEngType (G3) index sounds of the X360 TRAFFIC_MB/ENV_COMMON_MB banks: a separate table that
# runtime/x360audio.c applies only when both converted banks validated (runtime/x360abk.c).
SEPARATE = {'pvehicle'}


def main():
    xb, pc = cv.Side(XBG, 'X360', '>'), cv.Side(PCG, 'PC', '<')
    sh = dict(xb.types); sh.update(pc.types); xb.parse(sh); pc.parse(sh)
    names = {hash32(c): c for c in WANT}
    recs = []
    for (file, vault, ck, kk), a in sorted(pc.colls.items(), key=lambda kv: kv[0][3]):
        if ck not in names or (file, vault, ck, kk) not in xb.colls or file != 'ATTRIBUTES.BIN':
            continue
        b = xb.colls[(file, vault, ck, kk)]
        cdef = xb.classes[ck][1]
        for fk, x in a['fields'].items():
            y = b['fields'].get(fk)
            if x[0] != 'L' or not y or y[0] != 'L':
                continue
            want = WANT[names[ck]]
            if want is not None and fk not in {hash32(n) for n in want}:
                continue
            if cv.atom_eq(x[2][0], y[2][0])[0]:
                continue
            dt, off, sz, mc, fl, al = cdef[fk]
            # the X360 value bytes: re-read from its layout block
            V = [v for v in xb.vaults if v.file == file and v.name == vault][0]
            do = [d for k_, t, s, d in V.exports if t == cv.T_COLL and V.u32(V.vlt, d) == kk and V.u32(V.vlt, d + 4) == ck][0]
            lay = V.deref(0, do + 0x1c)
            raw = bytes(V.bufs[lay[0]][lay[1] + off: lay[1] + off + sz])
            recs.append((ck, kk, off, raw[::-1], names[ck], fk))
    with open(OUT, 'w') as f:
        f.write('// Generated by tools_snapshot/x360audio_attrib.py from the X360 ATTRIBUTES.BIN (little-endian). Do not edit.\n')
        f.write('typedef struct { uint32_t cls, key, off, len; uint8_t data[8]; } X360AttribPatch;\n')
        for table, sep in (('k_audio_patch', False), ('k_traffic_patch', True)):
            f.write('static const X360AttribPatch %s[] = {\n' % table)
            for ck, kk, off, raw, cn, fk in recs:
                if (cn in SEPARATE) == sep:
                    f.write('    {0x%08Xu, 0x%08Xu, %d, %d, {%s}},   // %s 0x%08x\n' % (ck, kk, off, len(raw), ','.join(str(x) for x in raw), cn, fk))
            f.write('};\n')
    print(len(recs), 'records')


main()
