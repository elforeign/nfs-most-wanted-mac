"""Generate/check the R23/R24 little-endian field overlay from the vault field-diff TSV.

Run with the project Python and -I. tools/gen_tables.py writes the TSV (tools_snapshot/vaults/compare_vaults.py on the
player's GLOBAL folders) and the table into runtime/gen/. --check compares every table byte with the TSV's X360 side;
--table allows checking a deliberately corrupted copy.
"""
import argparse
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parents[1]
TSV = ROOT / "runtime/gen/vaults/attrib_field_diffs.tsv"
TABLE = ROOT / "runtime/gen/attrib_light_data.inc"
TOD = 0x399ED882
FLARE = 0xC7C5806D
QUARTET = {0x3DCFA673, 0xB902CFAD, 0x59C373C3, 0xD835D0C8}
OFFSETS = {
    TOD: {0x5855B1E7: 0, 0x7623FEB2: 0x10, 0x52194D72: 0x20, 0xC91C60C7: 0x30},
    FLARE: {0x05B98B2C: 0, 0x1A0B5461: 0x10, 0x0FA46807: 0x14,
            0x96E40580: 0x18, 0xF093AACF: 0x1C, 0x07C20250: 0x20,
            0xF7649E63: 0x24, 0xA02742A6: 0x28},
}


def source_rows(tsv=TSV):
    lines = [line.split("\t") for line in Path(tsv).read_text().splitlines()]
    rows = []
    for values in lines[1:]:
        assert len(values) == len(lines[0]), "malformed TSV row"
        r = dict(zip(lines[0], values))
        if r["class"].lower() not in ("0x399ed882", "0xc7c5806d"):
            continue
        cls, key, field = (int(r[n], 16) for n in ("class", "collection", "field_hash"))
        if cls not in OFFSETS or (cls == TOD and key not in QUARTET):
            continue
        assert r["where"] == "L" and r["kind"] == "value"
        if r["type"] == "Attrib::Types::Vector4":
            data = struct.pack("<4f", *(float(x) for x in r["x360_value"].split(",")))
        elif r["type"] == "EA::Reflection::Float":
            data = struct.pack("<f", float(r["x360_value"]))
        elif r["type"] == "EA::Reflection::UInt32":
            data = struct.pack("<I", int(r["x360_value"], 0))
        else:
            raise ValueError(r["type"])
        rows.append((cls, key, OFFSETS[cls][field], data))
    assert len({(c, k, o) for c, k, o, _ in rows}) == len(rows)
    for cls, count, size, records in ((TOD, 11, 176, 4), (FLARE, 32, 296, 15)):
        part = [r for r in rows if r[0] == cls]
        assert len(part) == count and sum(len(r[3]) for r in part) == size
        assert len({r[1] for r in part}) == records
    return rows


def generate(rows):
    out = ["// Generated by recomp/lighting_data.py from attrib_field_diffs.tsv; do not edit.",
           "// Raw X360 values: R23 active quartet 11 vectors / 176 B; R24 32 fields / 296 B.",
           "static const struct { uint32_t cls, key, off, len; uint8_t data[16]; } k_light_patch[] = {"]
    for cls, key, off, data in rows:
        out.append(f"    {{0x{cls:08X}u, 0x{key:08X}u, 0x{off:02X}, {len(data)}, {{" +
                   ",".join(f"0x{x:02X}" for x in data) + "}},")
    return "\n".join(out + ["};", ""])


def check(path, expected):
    pattern = r"\{0x([0-9A-F]+)u, 0x([0-9A-F]+)u, 0x([0-9A-F]+), (\d+), \{([^}]+)\}\},"
    actual = []
    for cls, key, off, size, raw in re.findall(pattern, path.read_text()):
        data = bytes(int(x, 16) for x in raw.split(","))
        assert len(data) == int(size), "field length differs"
        actual.append((int(cls, 16), int(key, 16), int(off, 16), data))
    assert actual == expected, "patch table differs from TSV X360 bytes/keys/offsets"
    # Also reject extra/unparsed source that could change the compiled table.
    assert path.read_text() == generate(expected), "generated table source differs"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--table", type=Path, default=TABLE)
    parser.add_argument("--tsv", type=Path, default=TSV)
    args = parser.parse_args()
    expected = source_rows(args.tsv)
    if args.check:
        check(args.table, expected)
        print("PASS: R23 11 vectors / 4 records / 176 B; R24 32 fields / 15 records / 296 B; all 472 bytes equal TSV X360")
    else:
        args.table.write_text(generate(expected))
        print(f"Generated {args.table}: 43 patches / 472 bytes")


if __name__ == "__main__":
    main()
